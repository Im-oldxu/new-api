export type HeaderNavModules = {
  home: boolean
  console: boolean
  docs: boolean
  about: boolean
}

const DEFAULT_HEADER_NAV_MODULES: HeaderNavModules = {
  home: true,
  console: true,
  docs: true,
  about: true,
}

export function parseHeaderNavBoolean(
  raw: unknown,
  fallback: boolean
): boolean {
  if (typeof raw === 'boolean') return raw
  if (typeof raw === 'number') {
    if (raw === 1) return true
    if (raw === 0) return false
    return fallback
  }
  if (typeof raw === 'string') {
    const normalized = raw.trim().toLowerCase()
    if (normalized === 'true' || normalized === '1') return true
    if (normalized === 'false' || normalized === '0') return false
  }
  return fallback
}

function parseHeaderNavRecord(raw: unknown): Record<string, unknown> | null {
  if (!raw || String(raw).trim() === '') return null
  if (raw && typeof raw === 'object') return raw as Record<string, unknown>

  try {
    return JSON.parse(String(raw)) as Record<string, unknown>
  } catch {
    return null
  }
}

export function parseHeaderNavModules(raw: unknown): HeaderNavModules {
  const parsed = parseHeaderNavRecord(raw)
  return {
    home: parseHeaderNavBoolean(parsed?.home, DEFAULT_HEADER_NAV_MODULES.home),
    console: parseHeaderNavBoolean(parsed?.console, DEFAULT_HEADER_NAV_MODULES.console),
    docs: parseHeaderNavBoolean(parsed?.docs, DEFAULT_HEADER_NAV_MODULES.docs),
    about: parseHeaderNavBoolean(parsed?.about, DEFAULT_HEADER_NAV_MODULES.about),
  }
}

export function parseHeaderNavModulesFromStatus(
  status: Record<string, unknown> | null
): HeaderNavModules {
  return parseHeaderNavModules(status?.HeaderNavModules)
}
